"""Extract parameters/buffers from ExportedProgram and pack into a contiguous f32 blob."""

from __future__ import annotations

from typing import Any, Iterable

import numpy as np
import torch
import torch.export

# Every tensor in weights.f32.bin starts on a 4-byte boundary. All packing paths
# (torch pack_weights, the ONNX backend's initializer packing, and branch-blob
# concatenation in kuma.branch_assembly) go through append_aligned so the alignment
# rule lives in exactly one place.
WEIGHT_ALIGNMENT = 4


def append_aligned(blob: bytearray, raw: bytes) -> int:
    """Zero-pad `blob` up to WEIGHT_ALIGNMENT, append `raw`, return its byte offset."""
    pad = (-len(blob)) % WEIGHT_ALIGNMENT
    if pad:
        blob.extend(b"\x00" * pad)
    offset = len(blob)
    blob.extend(raw)
    return offset


def pack_f32_arrays(items: Iterable[tuple[str, np.ndarray]]) -> tuple[bytes, list[dict[str, Any]]]:
    """Pack (name, array) pairs, in the given order, as little-endian f32 into one
    aligned blob. Returns (blob, manifest weight entries)."""
    blob = bytearray()
    entries: list[dict[str, Any]] = []
    for name, arr_orig in items:
        arr = np.asarray(arr_orig).astype("<f4", copy=False).reshape(-1)
        raw = arr.tobytes()
        offset = append_aligned(blob, raw)
        entries.append(
            {
                "name": name,
                "shape": list(np.shape(arr_orig)),
                "dtype": "float32",
                "byte_offset": offset,
                "byte_length": len(raw),
                "n_elements": int(arr.size),
            }
        )
    return bytes(blob), entries


def _is_synthesized_dft_basis(name: str) -> bool:
    """Tensors named `<...>.complex_tucker.lifted_tensor_<i>` are fixed DFT/iDFT basis
    matrices that torch.export lifts out of the complex-Tucker spectral layers. They are
    deliberately NOT packed into weights.f32.bin: kuma-bart regenerates them from the
    weight name + shape alone (kuma-bart/src/engine/synthetic_weights.ts matches the same
    `.complex_tucker.lifted_tensor_(\\d+)$` pattern -- indices 0/1 are the complex iFFT
    cos/sin bases, 2/3 the irfft bases). This is a cross-repo coupling: renaming either
    side's pattern, or changing which index means which basis, silently breaks the other
    (the placeholder would reference a weight that is in neither the blob nor the
    synthesizer)."""
    return ".complex_tucker.lifted_tensor_" in name


def pack_weights(
    ep: torch.export.ExportedProgram,
) -> tuple[bytes, list[dict[str, Any]], list[str]]:
    """
    Pack all float32 parameters (and any float32 constants/buffers) into one binary blob.

    Layout: tensors are sorted by name, each 4-byte aligned.

    Returns:
        blob      — raw bytes (little-endian float32)
        entries   — list of dicts suitable for the manifest "weights" array
        skipped   — names of non-float32 tensors that were dropped (e.g. "name (torch.int64)")
    """
    # ep.state_dict holds lifted parameters and buffers
    all_tensors: dict[str, torch.Tensor] = dict(ep.state_dict)

    # ep.constants holds non-tensor constants and sometimes non-persistent buffers
    constants = getattr(ep, "constants", None) or {}
    for name, val in constants.items():
        if isinstance(val, torch.Tensor) and name not in all_tensors:
            all_tensors[name] = val

    to_pack: list[tuple[str, np.ndarray]] = []
    skipped: list[str] = []

    for name in sorted(all_tensors):
        tensor = all_tensors[name]

        # Regenerated by kuma-bart at load time; see _is_synthesized_dft_basis.
        if _is_synthesized_dft_basis(name):
            continue

        if tensor.dtype != torch.float32:
            # Non-float32 tensors (e.g. BN's num_batches_tracked: int64) are
            # training-only bookkeeping and not needed for inference.  Skip them
            # and surface them as warnings in the manifest rather than hard-failing.
            skipped.append(f"{name} ({tensor.dtype})")
            continue

        to_pack.append((name, tensor.detach().cpu().contiguous().numpy()))

    blob, entries = pack_f32_arrays(to_pack)
    return blob, entries, skipped
